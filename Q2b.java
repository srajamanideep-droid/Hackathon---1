/*2b) If-Else Condition:

Write a Java program to monitor the energy generated by a rooftop solar system. Read the energy generated in kWh.

If the energy generated is 10 kWh or more, display "Good Energy Generation".
Otherwise, display "Low Energy Generation".
Use an if-else statement.*/

import java.util.Scanner;
public class Q2b{
public static void main(String[] args){
Scanner sc=new Scanner(System.in);
System.out.println("Energy generated in kWh: ");
double d = sc.nextDouble();
if(d >= 10){
System.out.println("Good Energy Generation");
}
else{
System.out.println("Low Energy Generation");
}
}
}